/** 手机导航与统一弹框的真实浏览器回归；账号服务使用隔离 SQLite。 @author jingyh */
async (page) => {
    page.setDefaultTimeout(10000);
    const results = [], errors = [];
    const check = (value, name) => { if (!value) throw new Error(name); results.push(name); };
    page.on('pageerror', error => errors.push(error.message));
    const shot = name => page.screenshot({ animations: 'disabled', path: `D:/opensource/fn-lxserver/output/playwright/${name}.png` });
    try {
        await page.evaluate(() => localStorage.setItem('lx_agreement_accepted', 'true'));
        await page.reload();
        await page.waitForFunction(() => window.MobileShell && typeof settings !== 'undefined' && typeof currentListData !== 'undefined' && currentListData);
        await page.setViewportSize({ width: 1440, height: 900 });
        await page.evaluate(() => openCustomSourceModal());
        await page.locator('#custom-source-modal-content').waitFor({ state: 'visible' });
        check(await page.locator('#custom-source-modal-content .lx-dialog-heading').evaluate(n => n.getBoundingClientRect().height <= 50), '自定义源标题栏高度不超过 50px');
        check(await page.locator('#custom-source-modal-content').innerText().then(t => !t.includes('上传到')), '移除上传账号文案');
        check(await page.locator('#custom-sources-list').evaluate(n => getComputedStyle(n).padding === '10px'), '弹框内容四周 10px');
        await shot('source-modal-desktop');
        await page.locator('#custom-source-modal .lx-dialog-close').click();
        await page.locator('#custom-source-modal').waitFor({ state: 'hidden' });
        await page.evaluate(() => {
            window._currentCustomSourcesList = [{ id: 'layout-source', name: 'ikun音源[赞助][永久]', version: '26', supportedSources: ['git', 'kg', 'kw', 'tx', 'wy'], disabledSources: [] }];
            openEditSourceModal('layout-source');
        });
        const columns = () => page.locator('#edit-source-platform-list').evaluate(n => getComputedStyle(n).gridTemplateColumns.split(' ').length);
        check(await columns() === 3, '宽屏音源平台三列，五个平台只占两行');
        check(await page.locator('.edit-source-title-line').evaluate(n => Math.abs(n.querySelector('h3').getBoundingClientRect().top - n.querySelector('.edit-source-title-detail').getBoundingClientRect().top) < 10), '源名称版本与标题同一行');
        check(await page.locator('.lx-dialog-heading').first().evaluate(n => getComputedStyle(n, '::before').backgroundColor === 'rgb(49, 89, 219)'), '弹框标题左侧蓝条');
        await shot('source-platforms-desktop');
        await page.locator('#edit-source-modal').getByRole('button', { name: '全关闭' }).click();
        check(await page.locator('.platform-checkbox').evaluateAll(nodes => nodes.every(n => !n.checked)), '平台全关闭功能保留');
        await page.locator('#edit-source-platform-list .platform-toggle-item').first().locator('label > div').last().click();
        check(await page.locator('.platform-checkbox').evaluateAll(nodes => nodes[0].checked && nodes.slice(1).every(n => !n.checked)), '单个平台开关只改变目标平台');
        await page.locator('#edit-source-modal').getByRole('button', { name: '全启用' }).click();
        check(await page.locator('.platform-checkbox').evaluateAll(nodes => nodes.every(n => n.checked)), '平台全启用功能保留');
        await page.setViewportSize({ width: 390, height: 844 });
        check(await columns() === 1, '手机音源平台单列布局');
        check(await page.locator('#edit-source-modal-content').evaluate(n => n.getBoundingClientRect().left >= 0 && n.getBoundingClientRect().right <= innerWidth && n.scrollWidth <= n.clientWidth), '手机弹框无横向溢出');
        await shot('source-platforms-mobile');
        await page.locator('#edit-source-modal .lx-dialog-close').click();
        await page.locator('#edit-source-modal').waitFor({ state: 'hidden' });
        await page.locator('[data-mobile-tab="mobile-library"]').click();
        check(!await page.locator('#music-top-bar').isVisible() && !await page.locator('#main-sidebar').isVisible() && !await page.locator('#player-footer').isVisible(), '手机隐藏旧顶部、侧栏和播放栏');
        check(await page.locator('#view-mobile-library #tab-search').count() === 0, '音乐库菜单不含在线搜索');
        check(await page.locator('#mobile-library-favorites #tab-favorites').count() === 1 && await page.locator('#mobile-library-dislike #tab-dislike').count() === 1, '收藏和不喜欢各有独立卡片');
        const originalNode = await page.locator('#tab-recent').elementHandle();
        const imported = await page.evaluate(async () => {
            const playlists = Array.from({ length: 18 }, (_, index) => ({ id: 'mobile-' + index, name: '手机布局歌单 ' + (index + 1), list: [] }));
            const response = await fetch('/api/music/playlists/import', { method: 'POST', headers: { ...getUserAuthHeaders(), 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'playList_v2', data: playlists }) });
            if (!response.ok) throw new Error(await response.text());
            const result = await response.json();
            const stored = await (await fetch('/api/user/list', { headers: getUserAuthHeaders() })).json();
            currentListData = stored; renderMyLists(stored);
            return stored.userList.length;
        });
        check(imported >= 18, '真实接口保存和回读 18 个歌单');
        await page.locator('#view-mobile-library').evaluate(n => { n.scrollTop = n.scrollHeight; });
        check(await page.locator('#mobile-library-playlists').evaluate(n => n.getBoundingClientRect().bottom <= document.getElementById('mobile-bottom-nav').getBoundingClientRect().top), '音乐库滚到底最后歌单不被底栏遮挡');
        await page.locator('#view-mobile-library').evaluate(n => { n.scrollTop = 0; });
        await shot('mobile-library-390');
        await page.locator('#mobile-page-header').getByRole('button', { name: '在线搜索' }).click();
        check(await page.locator('#view-search').isVisible() && await page.locator('[data-mobile-tab="search"]').getAttribute('aria-current') === 'page', '右上角搜索进入独立搜索页并选中搜索 tab');
        await page.locator('[data-mobile-tab="mobile-home"]').click();
        check(await page.locator('#view-mobile-home').isVisible(), '首页预留页可达');
        await page.locator('[data-mobile-tab="mobile-settings"]').click();
        check(await page.locator('#view-mobile-settings').isVisible(), '独立设置账号页可达');
        await shot('mobile-settings-390');
        await page.locator('.mobile-profile').click();
        check(await page.locator('#settings-section-account').isVisible(), '账号卡片打开原账号表单');
        await page.locator('#mobile-back').click();
        check(await page.locator('#view-mobile-settings').isVisible(), '设置子页返回账号设置首页');
        await page.locator('#view-mobile-settings').getByRole('button', { name: /修改密码/ }).click();
        check(await page.locator('#account-password-dialog .lx-dialog-close').isVisible(), '原生改密弹框也有统一关闭按钮');
        await page.locator('#account-password-dialog .lx-dialog-close').click();
        check(!await page.locator('#account-password-dialog').isVisible(), '原生弹框关闭仍执行原清理逻辑');
        await page.locator('[data-mobile-tab="mobile-library"]').click();
        await page.locator('#tab-recent').click();
        check(await page.locator('#view-recent').isVisible(), '音乐库最近播放菜单可达');
        await page.locator('[data-mobile-tab="mobile-library"]').click();
        await page.locator('.mobile-now-playing').click();
        await page.waitForFunction(() => document.body.classList.contains('player-detail-open'));
        check(await page.locator('#view-player-detail .player-transport').evaluate(n => getComputedStyle(n).alignItems === 'center'), '手机播放详情控制按钮垂直居中');
        await page.evaluate(() => toggleLyrics());
        await page.waitForFunction(() => !document.body.classList.contains('player-detail-open'));
        for (const width of [320, 767, 768, 1024, 1440, 390]) {
            await page.setViewportSize({ width, height: 844 });
            check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px 页面无横向溢出`);
            if (width >= 768) check(await originalNode.evaluate(n => document.getElementById('main-navigation').contains(n)), `${width}px 原菜单节点恢复桌面侧栏`);
            else check(await page.locator('#view-mobile-library #tab-recent').count() === 1, `${width}px 原菜单节点恢复手机页`);
        }
        await page.setViewportSize({ width: 1440, height: 900 });
        await page.evaluate(() => { switchTab('search'); const node = document.getElementById('player-source'); node.innerHTML = getSourceTag('tx') + getQualityTags({ quality: 'flac' }); node.classList.remove('hidden'); });
        check(await page.locator('#player-source').evaluate(n => getComputedStyle(n.children[0]).color !== getComputedStyle(n.children[1]).color), 'QQ 与无损颜色区分');
        check(await page.locator('#gl-sort-hash-btn, #sl-sort-hash-btn').count() === 0, '排序仍保留，移除多余井号按钮');
        check(await page.evaluate(() => [...document.querySelectorAll('dialog, .fixed.inset-0')].filter(n => n.querySelector('h2,h3,h4') && !n.closest('[id^="view-"]')).every(n => n.dataset.dialogChrome === 'true' && n.querySelector('.lx-dialog-close'))), '全部静态业务弹框均有统一标题和关闭入口');
        await page.evaluate(() => { window.__mobileConfirmResult = 'pending'; showSelect('关闭测试', '取消后返回原页面').then(value => { window.__mobileConfirmResult = value; }); });
        const dynamic = page.locator('.lx-dialog-panel').filter({ hasText: '关闭测试' });
        await dynamic.locator('.lx-dialog-close').click();
        await page.waitForFunction(() => window.__mobileConfirmResult === false);
        check(true, '动态确认框关闭执行原取消回调');
        await page.setViewportSize({ width: 390, height: 844 });
        await page.reload();
        await page.waitForFunction(() => window.MobileShell && typeof currentListData !== 'undefined' && currentListData);
        await page.waitForTimeout(800);
        check(await page.locator('#mobile-bottom-nav').isVisible() && await page.locator('#view-mobile-library').isVisible(), '手机直接刷新默认进入音乐库');
        if (await page.locator('#favorites-children').evaluate(n => n.getBoundingClientRect().height < 1)) await page.locator('#tab-favorites').click();
        await page.waitForTimeout(320);
        check(await page.locator('#favorites-children').evaluate(n => n.getBoundingClientRect().height > 0), '手机收藏分组可以展开');
        await page.locator('#my-lists-container [data-sidebar-list-id="love"]').click();
        check(await page.locator('#view-search').isVisible(), '收藏子列表打开歌曲页');
        await page.waitForTimeout(60);
        check(await page.locator('[data-mobile-tab="mobile-library"]').getAttribute('aria-current') === 'page', '收藏歌曲页仍选中音乐库');
        await page.locator('#mobile-back').click();
        check(await page.locator('#view-mobile-library').isVisible(), '收藏歌曲页返回音乐库');
        await page.setViewportSize({ width: 667, height: 390 });
        check(await page.locator('#mobile-bottom-nav').evaluate(n => n.getBoundingClientRect().bottom <= innerHeight), '手机横屏底栏在视口内');
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '手机横屏无横向溢出');
        await page.setViewportSize({ width: 390, height: 844 });
        await page.locator('#view-mobile-library').evaluate(n => { n.scrollTop = 0; });
        await shot('mobile-library-390');
        await page.locator('[data-mobile-tab="mobile-settings"]').click();
        check(await page.locator('#view-mobile-settings').evaluate(n => n.scrollWidth <= n.clientWidth), '手机设置页内部无横向溢出');
        await shot('mobile-settings-390');
        check(errors.length === 0, `无脚本异常：${errors.join('; ')}`);
        return { passed: results.length, results };
    } catch (error) { await shot('mobile-polish-failure'); throw new Error(`最后通过：${results.at(-1)}；${error.message}`); }
}
