/** 歌单样式与播放栏的真实浏览器回归；在隔离实例登录后运行。 @author jingyh */
async page => {
  const results = [], errors = []
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name) }
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.waitForFunction(() => typeof currentListData !== 'undefined' && currentListData?.userList)
  await page.evaluate(async () => {
    currentListData.userList = currentListData.userList.filter(list => !['浏览器封面歌单', '修改后的封面歌单'].includes(list.name));
    await pushDataChange(); renderMyLists(currentListData);
  })
  if (await page.getByRole('button', { name: '我已阅读并接受' }).isVisible()) await page.getByRole('button', { name: '我已阅读并接受' }).click()
  await page.getByRole('button', { name: '新建或导入歌单' }).click()
  await page.locator('#playlist-actions-menu').getByRole('menuitem', { name: '新建', exact: true }).click()
  check(await page.locator('#playlist-editor').isVisible(), '侧栏新建入口打开封面编辑器')
  await page.locator('#playlist-editor-name').fill('浏览器封面歌单')
  await page.locator('#playlist-editor-file').setInputFiles({ name: 'invalid.png', mimeType: 'image/png', buffer: Buffer.from('invalid image') })
  await page.waitForFunction(() => document.getElementById('playlist-editor-error').textContent.includes('无效'))
  check(!await page.locator('#playlist-editor [type="submit"]').isDisabled(), '无效图片报错后恢复操作')
  await page.locator('#playlist-editor-file').setInputFiles('output/playwright/playlist-cover-fixture.png')
  await page.waitForFunction(() => document.getElementById('playlist-editor-preview').src.startsWith('data:image/png') && !document.querySelector('#playlist-editor [type="submit"]').disabled)
  check(await page.locator('#playlist-editor-preview').evaluate(img => img.naturalWidth > 0), '真实图片上传后预览成功')
  await page.screenshot({ path: 'output/playwright/playlist-editor-desktop.png' })
  const saved = page.waitForResponse(res => res.url().includes('/api/user/list') && res.request().method() === 'POST')
  await page.locator('#playlist-editor [type="submit"]').click()
  check((await saved).ok(), '新建歌单真实保存接口成功')
  const row = page.locator('#playlist-lists-container [data-sidebar-list-id]').filter({ hasText: '浏览器封面歌单' })
  await row.waitFor()
  const listId = await row.getAttribute('data-sidebar-list-id')
  check((await row.locator('img').getAttribute('src')).startsWith('data:image/png'), '左侧歌单显示上传封面')
  await row.click()
  check(!await page.locator('.library-search').isVisible() && !await page.locator('#song-search-controls').isVisible(), '歌单页面隐藏两个顶部搜索框')
  await row.getByRole('button', { name: '歌单操作', exact: true }).click()
  check(await page.getByRole('menuitem', { name: '编辑', exact: true }).isVisible() && await page.getByRole('menuitem', { name: '删除', exact: true }).isVisible(), '三个点下拉包含编辑和删除')
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  check(await page.locator('#playlist-editor-name').inputValue() === '浏览器封面歌单', '编辑回填歌单名称')
  await page.locator('#playlist-editor-name').fill('修改后的封面歌单')
  await page.locator('#playlist-editor [data-remove]').click()
  const edited = page.waitForResponse(res => res.url().includes('/api/user/list') && res.request().method() === 'POST')
  await page.locator('#playlist-editor [type="submit"]').click()
  check((await edited).ok(), '歌单编辑真实保存成功')
  await page.waitForFunction(id => currentListData.userList.find(l => l.id === id)?.name === '修改后的封面歌单', listId)
  check(await page.evaluate(id => currentListData.userList.find(l => l.id === id).cover === '', listId), '移除封面并编辑名称成功')
  for (const tab of ['search', 'songlist', 'leaderboard', 'recent', 'localmusic', 'downloads', 'settings']) {
    await page.evaluate(tab => switchTab(tab), tab)
    check(await page.locator('.library-search').isVisible() === (tab === 'search'), `${tab} 页顶部搜索显隐正确`)
  }
  await page.evaluate(() => { window.settingsPageToggle?.discard(); switchTab('search') })
  check(await page.locator('#song-search-controls').isVisible(), '在线搜索保持自己的歌曲搜索框')
  await page.evaluate(() => {
    updatePlayerInfo({ id: 'bar-fixture', name: '底栏测试歌曲', singer: '测试歌手', source: 'wy', meta: {} });
    window.playerBar.setLyrics([{ text: '歌词第一句' }, { text: '歌词第二句' }, { text: '歌词第三句' }]);
    window.playerBar.updateLyrics(1);
  })
  check(await page.locator('#player-lyric-current').innerText() === '歌词第二句' && await page.locator('#player-lyric-next').innerText() === '歌词第三句', '底栏同步显示当前与下一行歌词')
  await page.screenshot({ path: 'output/playwright/playlist-player-lyrics.png' })
  await page.locator('#player-title').click()
  check(await page.locator('#view-player-detail').isVisible(), '点击底栏标题打开播放页')
  await page.evaluate(() => toggleLyrics(true))
  await page.waitForTimeout(700)
  await page.locator('#player-more-btn').click()
  check(!await page.locator('#view-player-detail').isVisible() && await page.locator('#player-more-menu').isVisible(), '更多按钮只打开菜单')
  await page.evaluate(() => closePlayerPopovers())
  await page.locator('#progress-container').click()
  check(!await page.locator('#view-player-detail').isVisible(), '进度条点击不打开播放页')
  await page.locator('#player-artist').click()
  check(await page.locator('#view-player-detail').isVisible(), '点击底栏歌手打开播放页')
  await page.evaluate(() => toggleLyrics(true)); await page.waitForTimeout(700)
  await page.evaluate(() => { void window.PlaylistEditor.open({ name: '手机封面布局' }) })
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.locator('#playlist-editor').evaluate(el => el.getBoundingClientRect().width <= innerWidth), '手机弹窗宽度无溢出')
  await page.screenshot({ path: 'output/playwright/playlist-editor-mobile.png' })
  await page.keyboard.press('Escape')
  check(!await page.locator('#playlist-editor').count(), 'Esc 取消编辑并释放弹窗')
  await page.setViewportSize({ width: 1440, height: 900 })
  const deletingRow = page.locator(`[data-sidebar-list-id="${listId}"]`)
  await deletingRow.getByRole('button', { name: '歌单操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  const deleted = page.waitForResponse(res => res.url().includes('/api/user/list') && res.request().method() === 'POST')
  await page.getByRole('dialog', { name: '删除歌单', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  check((await deleted).ok(), '下拉删除经确认后真实保存成功')
  await page.waitForFunction(id => !currentListData.userList.some(l => l.id === id), listId)
  check(errors.length === 0, '页面脚本无异常：' + errors.join('; '))
  console.log(JSON.stringify({ passed: results.length, results, errors }))
}
