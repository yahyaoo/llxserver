/** 搜索、在线歌单和本地音乐操作验证；外部音源使用固定数据，保存使用真实服务。 */
async (page) => {
  const results = [], check = (value, label) => { if (!value) throw new Error(label); results.push(label) }
  try {
  await page.reload()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.waitForFunction(() => window.SongActions && currentListData)
  await page.evaluate(() => document.getElementById('project-agreement-modal')?.classList.add('hidden'))
  const song = { id: 'wy_9001', songmid: '9001', source: 'wy', name: '跨页面测试歌曲', singer: '跨页面测试歌手', albumName: '跨页面测试专辑', interval: '03:30', meta: { songId: '9001', albumName: '跨页面测试专辑' } }
  await page.evaluate(async item => { if (window.SongActions.isLoved(item)) await window.SongActions.toggleLove(item) }, song)
  await page.route('**/api/music/search?**', route => route.fulfill({ json: [song] }))
  await page.locator('#tab-search').click()
  await page.evaluate(() => { document.getElementById('search-source').value = 'wy' })
  await page.locator('#search-input').click()
  await page.locator('#search-input').fill('跨页面测试歌曲')
  await page.evaluate(async () => { await doSearch() })
  await page.waitForFunction(() => document.querySelector('#search-results .song-row-actions'))
  check(await page.locator('#search-results .song-row-actions').evaluate(node => getComputedStyle(node).opacity === '1' && [...node.querySelectorAll(':scope > button')].filter(button => getComputedStyle(button).display !== 'none').length === 2), '在线搜索只显示喜欢和更多')
  await page.evaluate(async item => { if (window.SongActions.isLoved(item)) await window.SongActions.toggleLove(item); window.SongActions.refresh() }, song)
  await page.waitForFunction(() => document.querySelector('#search-results .song-love-btn').getAttribute('aria-pressed') === 'false')
  await page.locator('#search-results .song-love-btn').click()
  await page.waitForFunction(() => document.querySelector('#search-results .song-love-btn').getAttribute('aria-pressed') === 'true')
  await page.waitForFunction(async () => { const response = await fetch('/api/user/list', { headers: getUserAuthHeaders() }); return (await response.json()).loveList.some(item => item.id === 'wy_9001') })
  check(await page.locator('#playlist-add-modal').evaluate(node => node.classList.contains('hidden')), '在线搜索喜欢直接保存，不弹框')
  await page.route('**/api/music/songList/detail?**', route => route.fulfill({ json: { info: { id: 'test-list', name: '跨页面测试歌单', source: 'wy', author: '测试作者' }, list: [song], total: 1 } }))
  await page.locator('#tab-songlist').click()
  await page.evaluate(() => window.SongListManager.openDetail('test-list', 'wy'))
  await page.waitForFunction(() => document.querySelector('#sl-detail-list .song-love-btn'))
  check(await page.locator('#sl-detail-list .song-love-btn').getAttribute('aria-pressed') === 'true', '在线歌单与搜索同步显示已喜欢')
  check(await page.locator('#sl-detail-list .song-row-actions').evaluate(node => getComputedStyle(node).opacity === '1' && [...node.querySelectorAll(':scope > button')].filter(button => getComputedStyle(button).display !== 'none').length === 2), '在线歌单只显示喜欢和更多')
  await page.locator('#sl-detail-list .song-love-btn').click()
  await page.waitForFunction(() => document.querySelector('#sl-detail-list .song-love-btn').getAttribute('aria-pressed') === 'false')
  check(true, '在线歌单直接取消喜欢')
  await page.evaluate(() => window.SongListManager.closeDetail())
  await page.waitForFunction(() => document.getElementById('songlist-detail-view').classList.contains('hidden'))
  await page.route('**/api/music/cache/list*', route => route.fulfill({ json: { success: true, data: [{ ...song, filename: '测试.mp3', folder: 'music', quality: '128k', album: song.albumName, songInfo: song, size: 1000 }] } }))
  await page.locator('#tab-localmusic').click()
  await page.evaluate(async () => { window.LocalMusicManager.isCustomDirMode = false; await window.LocalMusicManager.fetchData() })
  await page.waitForFunction(() => document.querySelector('#lm-list-container .song-love-btn'))
  check(await page.locator('#lm-list-container .song-love-btn').count() === 1, '音乐库包含直接喜欢按钮')
  await page.locator('#lm-list-container .song-love-btn').click()
  await page.waitForFunction(() => document.querySelector('#lm-list-container .song-love-btn').getAttribute('aria-pressed') === 'true')
  check(await page.locator('#playlist-add-modal').evaluate(node => node.classList.contains('hidden')), '已关联的本地音乐直接喜欢，不弹框')
  await page.locator('#lm-list-container [data-library-more]').click()
  await page.getByRole('menuitem', { name: '添加到歌单', exact: true }).click()
  await page.waitForFunction(() => !document.getElementById('playlist-add-modal').classList.contains('hidden'))
  check(true, '音乐库加号继续选择歌单')
  await page.evaluate(() => closePlaylistAddModal())
  await page.waitForFunction(() => document.getElementById('playlist-add-modal').classList.contains('hidden'))
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.locator('#lm-list-container .song-row-actions').evaluate(node => { const parent = node.closest('[data-lm-row-index]').getBoundingClientRect(); return [...node.querySelectorAll('button')].every(button => button.getBoundingClientRect().right <= parent.right + 1) }), '手机音乐库操作不溢出')
  await page.screenshot({ path: 'D:/opensource/fn-lxserver/output/playwright/song-actions-library-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('#lm-list-container .song-love-btn').click()
  await page.waitForFunction(() => document.querySelector('#lm-list-container .song-love-btn').getAttribute('aria-pressed') === 'false')
  check(true, '音乐库第二次点击喜欢可取消并清理测试状态')
  await page.locator('#tab-leaderboard').click()
  await page.waitForFunction(() => document.querySelector('#lb-row-0 .song-row-actions'))
  check(await page.locator('#lb-row-0 .song-row-actions').evaluate(node => [...node.querySelectorAll(':scope > button')].filter(button => getComputedStyle(button).display !== 'none').length === 2), '桌面排行榜只显示喜欢和更多')
  await page.screenshot({ path: 'D:/opensource/fn-lxserver/output/playwright/song-actions-desktop.png' })
  return { passed: results.length, results }
  } catch (error) { throw new Error(`已通过：${results.join('；')}；失败：${error.message}`) }
}
